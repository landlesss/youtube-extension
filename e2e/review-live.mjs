import {chromium} from 'playwright';
import {createRequire} from 'node:module';
import path from 'node:path';
import assert from 'node:assert/strict';
const {build}=createRequire(new URL('../extension/package.json',import.meta.url))('esbuild');
const bundle=await build({entryPoints:[path.resolve(import.meta.dirname,'../extension/src/content/ui.ts')],bundle:true,write:false,format:'iife',globalName:'reviewPreview'});
const out='/Users/macbookpro/.codex/visualizations/2026/10/31/01a19246-d474-7910-b074-7746fe7c889f';
const context=await chromium.launchPersistentContext('',{channel:'chromium',headless:false,viewport:{width:360,height:800},recordVideo:{dir:'/tmp/yt-review-live',size:{width:480,height:800}},args:[`--disable-extensions-except=${path.resolve(import.meta.dirname,'../extension/dist')}`,`--load-extension=${path.resolve(import.meta.dirname,'../extension/dist')}`]});
try{
const worker=context.serviceWorkers()[0]??await context.waitForEvent('serviceworker');
const id=new URL(worker.url()).host;
const yt=await context.newPage();
await yt.goto('https://www.youtube.com/watch?v=3Stflj2whx8',{waitUntil:'domcontentloaded',timeout:30000}).catch(e=>console.log('YouTube navigation:',e.message));
const page=await context.newPage();
await page.goto(`chrome-extension://${id}/sidepanel.html`);
// Render the shipped UI class with a long transcript, isolating layout from
// YouTube availability and backend quota. No ratings or feedback are submitted.
await page.evaluate(bundle.outputFiles[0].text + ";globalThis.reviewPreview=reviewPreview;");
await page.evaluate(()=>{
 const ui=new reviewPreview.SubtitlePanel({onLoadTranscript:async()=>Array.from({length:70},(_,i)=>({start:i*4,end:i*4+4,text:'Строка субтитров. Проверяем карточку отзыва и прокрутку длинного текста.'})),onSeek:()=>{}});
 ui.renderTracks([{languageCode:'ru',name:'Русский',baseUrl:'',isAutoGenerated:false}],null,{plan:'free',remaining:6});
 ui.showReviewToast();
});
const cdp=await context.newCDPSession(page);
for(const width of [360,260,480]){
 await page.setViewportSize({width,height:800});
 await page.waitForTimeout(1200);
 await page.screenshot({path:`${out}/review-live-${width}.png`});
 const snapshot=await cdp.send('DOMSnapshot.captureSnapshot',{computedStyles:[]});
 assert.ok(snapshot.strings.some(s=>s.includes('review-toast')));
 console.log('Rendered live review at width',width);
}
await page.waitForTimeout(1500);
const video=page.video();
await page.close();
await video.saveAs(`${out}/review-live.webm`);
console.log('Live headed UI recording saved. Transcript fixture; real shipped UI. No external submission.');
}finally{await context.close();}
